'use strict';
const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {CARS}=require('../catalog');
const {FIELDS}=require('../tuning');
const available=(()=>{try{return require.resolve('better-sqlite3')}catch{return null}})();
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'westrent-selfservice-'));
process.env.DATA_DIR=dir;
process.env.REQUIRE_IC_VERIFICATION='true'; // Ignorálva, a felület önkiszolgáló.
after(()=>fs.rmSync(dir,{recursive:true,force:true}));
test('81 eredeti V11 autó',()=>assert.equal(CARS.length,81));
test('regisztráció, önkiszolgáló bérlés, tuning és tulajdonosi bevétel', {skip:!available&&'better-sqlite3 nem telepített'},()=>{
 const db=require('../db');db.initDatabase();
 const tuning=Object.fromEntries(FIELDS.map(([key])=>[key,'Gyári']));
 const car={brand:'Audi',model:'R8',kind:'rental',price:50000,deposit:45000,rent_period:'day',tuning,description:'Teszt',publication_mode:'brokered'};
 const a=db.registerUser({ic_name:'Teszt Karakter',phone:'555001111',password:'safepassword111'});
 assert.equal(a.verified,false); // nincs jóváhagyás
 const listing=db.createOwnListing(a.id,car);assert.equal(listing.status,'active');assert.equal(listing.publication_mode,'private');assert.equal(db.listListings().total,1);
 const b=db.registerUser({ic_name:'Másik Karakter',phone:'555002222',password:'safepassword222'});
 const req=db.createRequest(b.id,{type:'rental',listing_id:listing.id,duration:'2 nap',budget:100000});
 assert.equal(req.status,'pending');assert.equal(db.receivedRequests(a.id)[0].phone,b.phone);
 assert.equal(db.updateOwnListing(a.id,listing.id,{action:'rented'}).status,'rented');
 assert.equal(db.listListings().total,1);assert.equal(db.listListings({status:'rented'}).total,1);
 assert.equal(db.listListings({status:'active'}).total,0);
 assert.throws(()=>db.createRequest(b.id,{type:'rental',listing_id:listing.id,duration:'2 nap',budget:100000}),/nem bérelhető/);
 assert.equal(db.updateOwnListing(a.id,listing.id,{action:'available'}).status,'active');
 const t=db.createTuningRequest(b.id,{brand:'Audi',model:'R8',tuning,notes:'IC egyeztetés'});
 assert.equal(db.ownerTuningRequests()[0].id,t.id);
 assert.equal(db.myTuningRequests(a.id).length,0);
 assert.equal(db.myTuningRequests(b.id).length,1);
 const i=db.saveIncome({description:'Vontató bérlés',gross:50000});
 assert.equal(i.tax,2500);assert.equal(i.net,47500);
 assert.equal(db.incomeReport().summary.net,47500);
 assert.ok(db.deleteIncome(i.id));assert.equal(db.incomeReport().summary.gross,0);
 assert.equal(db.updateOwnListing(a.id,listing.id,{action:'rented'}).status,'rented');
 assert.deepEqual(db.deleteOwnListing(a.id,listing.id),{ok:true});assert.equal(db.listListings().total,0);
 assert.throws(()=>db.deleteOwnListing(b.id,listing.id),/Nem található/);
});
