'use strict';
const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const os=require('node:os');
const fs=require('node:fs');
const path=require('node:path');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'westmta-v14-test-'));
process.env.DATA_DIR=dir;
process.env.REQUIRE_IC_VERIFICATION='true';
const db=require('../db');
const {CARS}=require('../catalog');
const {FIELDS}=require('../tuning');
after(()=>fs.rmSync(dir,{recursive:true,force:true}));
const tuning=Object.fromEntries(FIELDS.map(([key])=>[key,'Gyári']));
const car={brand:'Audi',model:'R8',kind:'rental',price:23000,deposit:45000,rent_period:'day',tuning,description:'Teszt'};
test('V11 katalógus pontosan 81 autó',()=>{assert.equal(CARS.length,81);assert.ok(CARS.includes('Audi R8'))});
test('fiókok, IC ellenőrzés, magánhirdetés és céges közvetítés',()=>{
 db.initDatabase();
 const alice=db.registerUser({ic_name:'Teszt Alice',phone:'555001111',password:'safepassword1111'});
 assert.equal(alice.verified,false);
 assert.ok(alice.verification_code.length>=6);
 assert.equal(db.loginUser('555001111','bad'),null);
 assert.equal(db.loginUser('555001111','safepassword1111').id,alice.id);
 assert.throws(()=>db.createOwnListing(alice.id,{...car,publication_mode:'private'}),/ellenőriztetned/);
 db.verifyUser(alice.id);
 const privateListing=db.createOwnListing(alice.id,{...car,publication_mode:'private'});
 assert.equal(privateListing.status,'active');
 assert.equal(privateListing.approval_status,'approved');
 assert.equal(db.listListings().total,1);
 const agency=db.createOwnListing(alice.id,{...car,model:'RS6',publication_mode:'brokered'});
 assert.equal(agency.status,'pending');
 assert.equal(agency.approval_status,'pending');
 assert.equal(db.listListings().total,1);
 assert.equal(db.pendingBrokerages().length,1);
 assert.equal(db.myListings(alice.id).length,2);
 assert.throws(()=>db.reviewBrokerage(privateListing.id,'approved',15),/függő/);
 db.reviewBrokerage(agency.id,'approved',18);
 assert.equal(db.listListings().total,2);
 assert.equal(db.getListing(agency.id).commission_pct,18);
 const edited=db.updateOwnListing(alice.id,agency.id,{...car,model:'RS6',publication_mode:'brokered',price:28000});
 assert.equal(edited.status,'pending');
 assert.equal(db.listListings().total,1);
 const userB=db.registerUser({ic_name:'Teszt Bob',phone:'555002222',password:'safepassword2222'});
 assert.throws(()=>db.updateOwnListing(userB.id,privateListing.id,{action:'withdraw'}),/saját/);
 assert.throws(()=>db.createOwnListing(alice.id,{...car,kind:'sale',publication_mode:'private'}),/kizárólag autóbérlésre/);
 assert.throws(()=>db.createRequest(userB.id,{type:'quote',car_name:'BMW M4 F82',duration:'2 nap',budget:40000}),/Csak autóbérlési/);
 const req=db.createRequest(userB.id,{type:'rental',listing_id:privateListing.id,car_name:'Hamis autó',duration:'2 nap',budget:40000,description:'Érdekel'});
 assert.equal(req.status,'pending');
 assert.equal(db.myRequests(userB.id).length,1);
 assert.equal(db.myRequests(userB.id)[0].car_name,'Audi R8');
 assert.equal(db.receivedRequests(alice.id).length,1);
 assert.equal(db.receivedRequests(userB.id).length,0);
 assert.throws(()=>db.reviewPrivateRequest(userB.id,req.id,'approved'),/Nem található saját/);
 assert.equal(db.reviewPrivateRequest(alice.id,req.id,'approved').status,'approved');
 assert.equal(db.reviewRequest(req.id,'completed').status,'completed');
 const sess=db.createSession(alice.id);
 assert.equal(db.findSession(sess).id,alice.id);
 db.removeSession(sess);
 assert.equal(db.findSession(sess),null);
});
